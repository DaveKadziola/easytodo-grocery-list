async def test_item_stays_on_its_categorys_board(db):  # triage #10
    owner = await create_user(db)
    board = await create_board(db, owner)
    other = await create_board(db, owner, "Other")
    category = await create_category(db, board)
    item = await create_item(db, category)
    other_id, item_id, category_id = other.id, item.id, category.id
    updated_at = item.updated_at

    with pytest.raises(IntegrityError, match="fk_items_category_id_board_id_categories"):
        await db.execute(update(Item).where(Item.id == item_id).values(board_id=other_id))
    await db.rollback()

    # Moving the category takes its items along, without touching their updated_at.
    await db.execute(update(Category).where(Category.id == category_id).values(board_id=other_id))
    await db.commit()
    row = (await db.execute(select(Item.board_id, Item.updated_at))).one()
    assert tuple(row) == (other_id, updated_at)


async def test_foreign_keys_are_indexed(db):  # triage #11
    unindexed = await db.execute(
        text(
            """
            SELECT c.conrelid::regclass::text || '.' || c.conname
            FROM pg_constraint c
            WHERE c.contype = 'f'
              AND NOT EXISTS (
                SELECT 1 FROM pg_index i
                WHERE i.indrelid = c.conrelid AND i.indkey[0] = c.conkey[1]
              )
            ORDER BY 1
            """
        )
    )
    assert unindexed.scalars().all() == []


