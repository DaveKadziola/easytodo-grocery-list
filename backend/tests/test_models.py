async def test_downgrade_to_0001_keeps_archived_categories_under_unique_names(db):
    board = await create_board(db, await create_user(db))
    ids = []
    for position in (0, 1):  # two archived "Dairy": only the active names are unique
        category = await create_category(db, board, "Dairy", position)
        await db.execute(
            update(Category).where(Category.id == category.id).values(archived_at=func.now())
        )
        await db.commit()
        ids.append(category.id)
    await create_category(db, board, "Dairy", position=2)
    a, b = ids

    cfg = alembic_cfg()
    try:
        await asyncio.to_thread(command.downgrade, cfg, "0001")
        names = (await db.scalars(select(Category.name).order_by(Category.id))).all()
        assert names == [f"Dairy (archived {a})", f"Dairy (archived {b})", "Dairy"]
    finally:
        await db.rollback()  # an open transaction would block the ALTER of the upgrade
        await asyncio.to_thread(command.upgrade, cfg, "head")
