async def _count(db: AsyncSession, model: type) -> int:
    return await db.scalar(select(func.count()).select_from(model))


def _in(days: int) -> datetime:
    return datetime.now(UTC) + timedelta(days=days)


def _attachment(item: Item, uploaded_by: User, storage_key: str = "k" * 32) -> Attachment:
    return Attachment(
        item_id=item.id,
        filename="milk.png",
        kind="image",
        content_type="image/png",
        size_bytes=1024,
        storage_key=storage_key,
        uploaded_by=uploaded_by.id,
    )


async def _one_row_each(db: AsyncSession) -> None:
    """A user, a board, a category, an item, a sort preference, an attachment and a notification."""
    user = await create_user(db)
    board = await create_board(db, user)
    category = await create_category(db, board)
    item = await create_item(db, category)
    db.add_all(
        [
            CategorySortPref(
                user_id=user.id,
                category_id=category.id,
                open_first=True,
                field="name",
                descending=False,
            ),
            _attachment(item, user),
        ]
    )
    await db.commit()
    await create_notification(db, user, board=board)


