async def test_timestamps_default_to_insert_time(db):
    cat = await create_category(db, await create_board(db, await create_user(db)))
    i1 = await create_item(db, cat)
    await asyncio.sleep(0.05)
    i2 = await create_item(db, cat, "Eggs")
    assert i2.created_at > i1.created_at
    assert abs(i1.created_at - datetime.now(UTC)) < timedelta(seconds=5)
    assert i1.updated_at == i1.created_at


async def test_downgrade_to_base_and_back(_db_engine: AsyncEngine):
    cfg = alembic_cfg()
    await asyncio.to_thread(command.downgrade, cfg, "base")
    try:
        async with _db_engine.connect() as conn:
            tables = await conn.scalars(
                text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
            )
            enums = await conn.scalars(text("SELECT typname FROM pg_type WHERE typtype = 'e'"))
            assert (tables.all(), enums.all()) == (["alembic_version"], [])
    finally:
        await asyncio.to_thread(command.upgrade, cfg, "head")
