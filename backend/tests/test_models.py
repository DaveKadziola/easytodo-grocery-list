async def test_deleting_board_cascades(db):
    owner = await create_user(db)
    editor = await create_user(db, "editor@example.com")
    board = await create_board(db, owner, members={editor: BoardRole.EDITOR})
    category = await create_category(db, board)
    item = await create_item(db, category)
    await create_checklist_entry(db, item)
    db.add_all(
        [
            BoardInvite(
                board_id=board.id,
                token_hash="a" * 64,
                email="guest@example.com",
                role=BoardRole.VIEWER,
                created_by=owner.id,
                expires_at=_in(days=7),
            ),
            CategorySortPref(
                user_id=editor.id,
                category_id=category.id,
                open_first=False,
                field="created",
                descending=True,
            ),
            _attachment(item, editor),
        ]
    )
    await db.commit()
    await create_notification(db, editor, board=board)
    dependents = (
        Category,
        Item,
        BoardMember,
        BoardInvite,
        CategorySortPref,
        ChecklistEntry,
        Attachment,
    )
    assert [await _count(db, m) for m in dependents] == [1, 1, 2, 1, 1, 1, 1]

    await db.execute(delete(Board).where(Board.id == board.id))
    await db.commit()

    assert [await _count(db, m) for m in dependents] == [0] * 7
    assert await _count(db, User) == 2
    # A notification outlives its board: it only loses the link.
    assert (await db.scalars(select(Notification.board_id))).all() == [None]


async def test_deleting_user_cascades(db):
    user = await create_user(db)
    other = await create_user(db, "other@example.com")
    own_board = await create_board(db, user)
    await create_item(db, await create_category(db, own_board))
    shared_board = await create_board(db, other, "Shared", members={user: BoardRole.VIEWER})
    db.add_all(
        [
            UserSession(user_id=user.id, token_hash="b" * 64, expires_at=_in(days=30)),
            RecoveryCode(user_id=user.id, code_hash="c" * 64),
            PasswordResetToken(user_id=user.id, token_hash="d" * 64, expires_at=_in(days=1)),
            BoardInvite(
                board_id=shared_board.id,
                token_hash="e" * 64,
                role=BoardRole.EDITOR,
                created_by=user.id,
                expires_at=_in(days=7),
            ),
        ]
    )
    await db.commit()

    await db.execute(delete(User).where(User.id == user.id))
    await db.commit()

    for model in (UserSession, RecoveryCode, PasswordResetToken, BoardInvite, Category, Item):
        assert await _count(db, model) == 0, model.__name__
    assert (await db.scalars(select(Board.id))).all() == [shared_board.id]
    assert (await db.scalars(select(BoardMember.user_id))).all() == [other.id]


